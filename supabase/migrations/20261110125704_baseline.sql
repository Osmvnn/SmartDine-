create type public.reservation_status as enum ('pending','confirmed','cancelled','completed','no_show');
create type public.loyalty_point_type as enum ('earned','redeemed');

create table public.users (
  id integer generated by default as identity primary key,
  name varchar(100) not null,
  email varchar(100) not null unique,
  password varchar(255) not null,
  role public.user_role not null default 'customer',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.restaurant_tables (
  id integer generated by default as identity primary key,
  table_number integer not null unique,
  capacity integer not null default 4,
  status public.table_status not null default 'available',
  qr_token varchar(100) not null unique,
  waiter_id integer references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.table_sessions (
  id integer generated by default as identity primary key,
  table_id integer not null references public.restaurant_tables(id) on delete cascade,
  session_token varchar(255) not null,
  status public.session_status not null default 'active',
  started_at timestamptz not null default now(),
  ended_at timestamptz
);
create index table_sessions_table_status_idx on public.table_sessions(table_id,status);

create table public.menu_categories (
  id integer generated by default as identity primary key,
  name varchar(100) not null,
  description text,
  image_url varchar(255),
  created_at timestamptz not null default now()
);

create table public.menu_items (
  id integer generated by default as identity primary key,
  category_id integer not null references public.menu_categories(id) on delete cascade,
  name varchar(150) not null,
  description text,
  price numeric(10,2) not null check (price >= 0),
  image_url varchar(255),
  is_available boolean not null default true,
  stock_quantity integer not null default -1,
  prep_time_minutes integer not null default 15,
  dietary_tags varchar(255),
  created_at timestamptz not null default now()
);
create index menu_items_category_idx on public.menu_items(category_id);

create table public.menu_item_modifiers (
  id integer generated by default as identity primary key,
  menu_item_id integer not null references public.menu_items(id) on delete cascade,
  name varchar(100) not null,
  price_delta numeric(10,2) not null default 0,
  created_at timestamptz not null default now()
);

create table public.promo_codes (
  id integer generated by default as identity primary key,
  code varchar(50) not null unique,
  description varchar(255),
  discount_type public.discount_type not null,
  discount_value numeric(10,2) not null,
  min_order numeric(10,2) not null default 0,
  max_uses integer not null default 0,
  used_count integer not null default 0,
  is_active boolean not null default true,
  expires_at date,
  created_at timestamptz not null default now()
);

create table public.orders (
  id integer generated by default as identity primary key,
  table_id integer not null references public.restaurant_tables(id),
  session_id integer references public.table_sessions(id),
  customer_id integer references public.users(id) on delete set null,
  status public.order_status not null default 'pending',
  total numeric(10,2) not null default 0,
  notes text,
  promo_code_id integer references public.promo_codes(id) on delete set null,
  discount_amount numeric(10,2) not null default 0,
  payment_type public.payment_type not null default 'online',
  estimated_ready_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index orders_table_idx on public.orders(table_id);
create index orders_customer_idx on public.orders(customer_id);
create index orders_status_created_idx on public.orders(status,created_at desc);

create table public.order_items (
  id integer generated by default as identity primary key,
  order_id integer not null references public.orders(id) on delete cascade,
  menu_item_id integer not null references public.menu_items(id),
  quantity integer not null default 1 check(quantity > 0),
  notes text,
  price numeric(10,2) not null,
  status public.order_item_status not null default 'pending',
  modifiers text,
  modifier_total numeric(10,2) not null default 0,
  created_at timestamptz not null default now()
);
create index order_items_order_idx on public.order_items(order_id);

create table public.payments (
  id integer generated by default as identity primary key,
  order_id integer not null references public.orders(id) on delete cascade,
  amount numeric(10,2) not null,
  method public.payment_method not null default 'card',
  payment_timing public.payment_timing not null default 'pre',
  split_type public.split_type not null default 'full',
  payer_name varchar(100),
  status public.payment_status not null default 'pending',
  transaction_id varchar(100),
  tip_amount numeric(10,2) not null default 0,
  cashier_confirmed boolean not null default false,
  confirmed_by integer references public.users(id) on delete set null,
  confirmed_at timestamptz,
  waiter_confirmed_by integer references public.users(id) on delete set null,
  waiter_confirmed_at timestamptz,
  refund_reason varchar(255),
  refunded_by integer references public.users(id) on delete set null,
  refunded_at timestamptz,
  created_at timestamptz not null default now()
);
create index payments_order_idx on public.payments(order_id);

create table public.waiter_requests (
