create type public.table_status as enum ('available','occupied','reserved');
create type public.session_status as enum ('active','closed');
create type public.discount_type as enum ('percent','fixed');
create type public.order_status as enum ('pending','confirmed','preparing','ready','served','completed','cancelled');
create type public.payment_type as enum ('online','physical');
create type public.order_item_status as enum ('pending','preparing','ready','served');
create type public.payment_method as enum ('card','cash','mobile');
create type public.payment_timing as enum ('pre','post');
create type public.split_type as enum ('full','equal','custom');
create type public.payment_status as enum ('pending','paid','failed','refunded');
create type public.request_type as enum ('help','water','salt','cleaning','complaint','bill');
